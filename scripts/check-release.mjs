import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { command, scanFile, success } from './release-utils.mjs';

const manifest = JSON.parse(await readFile('package.json', 'utf8'));
const lock = JSON.parse(await readFile('package-lock.json', 'utf8'));
assert.equal(manifest.name, 'api-contract-diff');
assert.match(manifest.version, /^\d+\.\d+\.\d+-rc\.\d+$/);
assert.equal(manifest.license, 'MIT');
assert.equal(manifest.type, 'module');
assert.deepEqual(manifest.bin, { 'api-contract-diff': 'dist/cli.js' });
assert.equal(manifest.engines.node, '>=22');
assert.deepEqual(manifest.repository, { type: 'git', url: 'git+https://github.com/jigar48/api-contract-diff.git' });
assert.equal(manifest.homepage, 'https://github.com/jigar48/api-contract-diff#readme');
assert.equal(manifest.bugs.url, 'https://github.com/jigar48/api-contract-diff/issues');
assert.equal(lock.version, manifest.version);
assert.equal(lock.packages[''].version, manifest.version);
assert.deepEqual(lock.packages[''].dependencies, manifest.dependencies);
assert.ok((await readFile('src/cli.ts', 'utf8')).startsWith('#!/usr/bin/env node\n'));
const license = await readFile('LICENSE', 'utf8');
assert.match(license, /^MIT License/);
assert.match(license, /Permission is hereby granted, free of charge/);
assert.match(license, /THE SOFTWARE IS PROVIDED "AS IS"/);
const ignored = ['node_modules/probe', 'dist/probe', 'candidate.tgz', '.env', '.env.local', '.npmrc', 'private.key', 'private.pem', '.DS_Store'];
const ignoredOutput = success(command('git', ['check-ignore', '--stdin'], { input: `${ignored.join('\n')}\n` }), 'Ignore rules').trim().split(/\r?\n/);
assert.deepEqual(ignoredOutput.sort(), [...ignored].sort());
const result = command('git', ['ls-files', '--cached', '--others', '--exclude-standard', '-z']);
const files = [...new Set(success(result, 'Git inventory').split('\0').filter(Boolean))];
assert.ok(files.length > 0);
for (const file of files) await scanFile(file);
console.log(`Release metadata, MIT license, ignore rules: PASS; scanned ${files.length} Git candidate files for common credentials and local paths.`);
console.log('Secret scanning is heuristic and requires manual review; repository metadata targets jigar48/api-contract-diff.');
